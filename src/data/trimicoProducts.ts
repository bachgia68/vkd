export const findTrimicoProduct = (slug: string): TrimicoProduct | undefined =>
  trimicoProducts.find((p) => p.slug === slug);

export const formatVNDorContact = (price: number | null): string =>
  price == null ? 'Liên hệ' : new Intl.NumberFormat('vi-VN').format(price) + '₫';

// Chuẩn hóa theo tỉ giá dùng thống nhất toàn site (25.000 VND/USD, xem src/data/products.ts)
const VND_PER_USD = 25000;

export interface TrimicoCartCompatibleProduct {
  id: string;
  name: string;
  nameVi: string;
  category: string;
  healthGoal: HealthGoal;
  audiences: TargetAudience[];
  priceUSD: number;
  priceVND: number;
  priceJPY: number;
  priceCNY: number;
  priceEUR: number;
  activeIngredient: string;
  description: string;
  descriptionVi: string;
  image: string;
  badge: string;
  rating: number;
  reviews: number;
  familySafe?: boolean;
}

// Chỉ gọi khi product.price !== null (đã kiểm tra ở UI — SP "Liên hệ" không có nút Thêm Giỏ/Mua Ngay).
export function toTrimicoCartProduct(p: TrimicoProduct): TrimicoCartCompatibleProduct {
  const price = p.price ?? 0;
  const priceUSD = Math.round((price / VND_PER_USD) * 100) / 100;
  return {
    id: p.sku,
    name: p.name,
    nameVi: p.name,
    category: p.category,
    healthGoal: p.healthGoal,
    audiences: p.audiences,
    priceUSD,
    priceVND: price,
    priceJPY: Math.round(priceUSD * 150),
    priceCNY: Math.round(priceUSD * 7.2 * 100) / 100,
    priceEUR: Math.round(priceUSD * 0.93 * 100) / 100,
    activeIngredient: p.ingredients ?? p.description.slice(0, 60),
    description: p.description,
    descriptionVi: p.description,
    image: p.image,
    badge: p.badge ?? '',
    rating: 0,
    reviews: 0,
    familySafe: p.familySafe,
  };
}
